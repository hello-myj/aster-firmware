#!/usr/bin/env python3
"""Convert RIFF PCM (chunk-aware wave parser) to flash mono PCM at 16 kHz."""
from pathlib import Path
import wave, struct
ROOT=Path(__file__).resolve().parent
NAMES=('tick','tap','open','close','tune')
GAIN=8  # +18.06 dB; source peaks are -21..-23 dBFS, preserving headroom.
def samples(path):
    with wave.open(str(path),'rb') as w:
        assert (w.getnchannels(),w.getsampwidth(),w.getframerate())==(1,2,22050)
        raw=w.readframes(w.getnframes())
    src=struct.unpack('<'+'h'*(len(raw)//2),raw)
    # Linear resampling; synthesized partials are all well below 8 kHz.
    result=[]
    for i in range(round(len(src)*16000/22050)):
        q,rem=divmod(i*22050,16000)
        value=round((src[q]*(16000-rem)+src[min(q+1,len(src)-1)]*rem)*GAIN/16000)
        assert -32768<=value<=32767, "source would clip; reduce GAIN"
        result.append(value)
    return result
def render():
    out=['/* Generated by flux-sounds/bake.py; mono PCM16 at 16000 Hz, +18 dB. */',
         'BUILD_ASSERT(CONFIG_ASTER_AUDIO_RATE == 16000 && CONFIG_ASTER_AUDIO_BITS == 16, "rebake FLUX sounds for native format");']
    for name in NAMES:
        data=samples(ROOT/(name+'.wav'))
        out.append('static const int16_t sound_'+name+'[] = {')
        out += [','.join(map(str,data[i:i+20]))+',' for i in range(0,len(data),20)]
        out.append('};')
    return '\n'.join(out)+'\n'
if __name__=='__main__': (ROOT.parent/'flux_sounds.inc').write_text(render())
