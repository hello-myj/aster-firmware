"""Bake FLUX chrome at actual device pixel sizes, without changing SDK fonts.

Uses licensed ui.ttf with native-ppem FreeType hinting. Glyphs
are immutable A8 in flash; arbitrary application names fall back to SD fonts.
"""
from pathlib import Path
import re
import math
import freetype
from build_cpfont import TTF_DEFAULT, ROOT, unpack_rows

SIZES = [8, 9, 10, 11, 12, 14, 16, 20, 22, 25, 30, 47, 50]

def main():
    source=(ROOT/"systems/zephyr/ui/launcher/flux.c").read_text()
    strings=re.findall(r'"([^"\n]*)"',source)
    cps=sorted(set(range(32,127)) | {ord(c) for s in strings for c in s if ord(c)>127})
    lines=["/* Generated by tools/build_flux_fonts.py; SPDX-License-Identifier: MIT.",
           " * Glyph artwork: resources/fonts/ui.ttf; see resources/fonts/NOTICE. */"]
    faces=[]
    for size in SIZES:
        coverage=cps
        # Large faces have specific jobs. Keep all ASCII for clock/metadata,
        # and only the title characters that can actually use each size.
        if size>=25:
            names=re.findall(r'\{"aster\.[^"]+","([^"]+)"',source)
            names+=re.findall(r'\.name="([^"]+)"',source)
            titles='流光文件' if size==25 else ''.join(names) if size==30 else ''
            coverage=sorted(set(range(32,127)) | {ord(c) for c in titles})
        # Hint at the actual device ppem. Rendering at 4x then reducing
        # distributes narrow strokes across pixels before the ribbon's own
        # transform samples them again. Keep full A8 coverage, without a
        # 4bpp pack/unpack quantization round trip.
        face=freetype.Face(str(TTF_DEFAULT))
        face.set_pixel_sizes(0,size)
        line_h=math.ceil(face.size.height/64)
        desc=math.floor(face.size.descender/64)
        bitmap=bytearray();records=[]
        for cp in coverage:
            index=face.get_char_index(cp) or face.get_char_index(0xfffd)
            face.load_glyph(index,freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
            g=face.glyph
            pixels,w,h=unpack_rows(g.bitmap)
            # Retain grayscale antialiasing. Trim only the faintest
            # fringe and gently increase coverage contrast, not a binary
            # threshold which would expose stair steps on curved strokes.
            pixels=bytes(max(0,min(255,round((v-16)*255/223))) for v in pixels)
            offset=len(bitmap);bitmap.extend(pixels)
            adv=(g.advance.x+32)//64
            records.append(f"{{{cp},{offset},{adv},{w},{h},{g.bitmap_left},{g.bitmap_top-h+1}}}")
        lines.append(f"static const uint8_t bitmap_{size}[]={{")
        for i in range(0,len(bitmap),32):
            lines.append(','.join(str(x) for x in bitmap[i:i+32])+',')
        lines.append('};')
        lines.append(f"static const flux_glyph_t glyphs_{size}[]={{"+','.join(records)+'};')
        lines.append(f"static const flux_face_t face_{size}={{glyphs_{size},bitmap_{size},sizeof(glyphs_{size})/sizeof(glyphs_{size}[0])}};")
        lines.append(f"static const lv_font_t font_{size}={{.get_glyph_dsc=flux_glyph_dsc,.get_glyph_bitmap=flux_glyph_bitmap,.line_height={line_h},.base_line={-desc},.static_bitmap=1,.dsc=&face_{size}}};")
        faces.append(f"{{{size},&font_{size}}}")
    lines.append('static const struct {uint8_t px;const lv_font_t *font;} fonts[]={'+','.join(faces)+'};')
    target=ROOT/'systems/zephyr/ui/launcher/flux_fonts.inc'
    target.write_text('\n'.join(lines)+'\n')
    print(f"{len(cps)} glyphs, {len(SIZES)} native sizes, {target.stat().st_size} source bytes")

if __name__=='__main__': main()
