"""Generate the ONE offline system-UI face family from licensed cpfont input.

The onboarding, settings and recovery screens share these fonts. Arbitrary APP
text continues to use the complete SD fonts. No FreeType or host font required.
"""
from pathlib import Path
import argparse
import re
import struct

ROOT=Path(__file__).resolve().parents[1]

def generate(output):
    text=(ROOT/'common/setup/ui-strings.txt').read_text(encoding='utf-8')
    for source in ['common/setup/aster_setup_core.c','systems/shared/setup/setup_ui.c','systems/zephyr/ui/wifi_settings.c','systems/zephyr/ui/qpanel.c']:
        data=(ROOT/source).read_text(encoding='utf-8')
        tokens=re.finditer(r'"(?:\\.|[^"\\])*"|/\*.*?\*/|//[^\n]*',data,re.S)
        text+=''.join(m[0][1:-1] for m in tokens if m[0].startswith('"'))
    cps=sorted(set(range(32,127))|{ord(c) for c in text if ord(c)>127})
    lines=['/* Generated by tools/build_system_fonts.py. SPDX-License-Identifier: MIT.',
           ' * Glyph artwork: resources/fonts; see resources/fonts/NOTICE. */','#include <lvgl.h>','#include "system_font.h"']
    for px in [16,20,24]:
        raw=(ROOT/f'resources/fonts/ui_{px}.cpfont').read_bytes()
        assert raw[:8]==b'CPFONT\0\0' and struct.unpack_from('<HH',raw,8)==(4,0)
        count,glyphs=struct.unpack_from('<II',raw,36);offset=struct.unpack_from('<I',raw,56)[0]
        intervals=[struct.unpack_from('<III',raw,offset+i*12) for i in range(count)]
        base=offset+count*12;bitmap_base=base+glyphs*16
        bitmap=bytearray();records=['{0}']
        for cp in cps:
            if cp==0x2026:
                w=px-2;h=2;levels=[15 if x in (1,2,w//2,w//2+1,w-3,w-2) else 0 for y in range(h) for x in range(w)]
                blob=bytes((levels[i]<<4)|(levels[i+1] if i+1<len(levels) else 0) for i in range(0,len(levels),2))
                records.append(f'{{.bitmap_index={len(bitmap)},.adv_w={px*16},.box_w={w},.box_h={h},.ofs_y=0}}')
                bitmap+=blob;continue
            lookup={0x2013:45,0x2014:45}.get(cp,cp)
            index=next((j+lookup-a for a,b,j in intervals if a<=lookup<=b),None)
            if index is None:raise ValueError(f'System UI font lacks U+{cp:04X}')
            w,h,advance,left,top,length,pos=struct.unpack_from('<BBHhhH2xI',raw,base+16*index)
            records.append(f'{{.bitmap_index={len(bitmap)},.adv_w={advance},.box_w={w},.box_h={h},.ofs_x={left},.ofs_y={top-h+1}}}')
            bitmap+=raw[bitmap_base+pos:bitmap_base+pos+length]
        lines.append(f'static const uint8_t bits_{px}[]={{')
        for i in range(0,len(bitmap),32):lines.append(','.join(map(str,bitmap[i:i+32]))+',')
        lines+=['};',f'static const lv_font_fmt_txt_glyph_dsc_t glyphs_{px}[]={{'+','.join(records)+'};',
                f'static const uint16_t unicode_{px}[]={{'+','.join(str(cp-32) for cp in cps)+'};',
                f'static const lv_font_fmt_txt_cmap_t cmap_{px}[]={{'+
                f'{{.range_start=32,.range_length={cps[-1]-31},.glyph_id_start=1,.unicode_list=unicode_{px},.list_length={len(cps)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}'+ '};',
                f'static const lv_font_fmt_txt_dsc_t data_{px}={{.glyph_bitmap=bits_{px},.glyph_dsc=glyphs_{px},.cmaps=cmap_{px},.cmap_num=1,.bpp=4,.bitmap_format=0}};']
        asc=struct.unpack_from('<h',raw,45)[0];height=raw[44]
        lines.append(f'static const lv_font_t font_{px}={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={height},.base_line={height-asc},.subpx=LV_FONT_SUBPX_NONE,.dsc=&data_{px}}};')
    lines.append('const lv_font_t *aster_system_font(uint8_t px){return px<18?&font_16:px<22?&font_20:&font_24;}')
    output.parent.mkdir(parents=True,exist_ok=True);output.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(f'System UI fonts: {len(cps)} glyphs at 16/20/24px -> {output}')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--output',type=Path,required=True)
    generate(parser.parse_args().output)
