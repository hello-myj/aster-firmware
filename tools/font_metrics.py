#!/usr/bin/env python3
"""Generate public font metrics from the firmware resource release.

Two questions, two owners. build_cpfont.py decides WHICH sizes exist and writes
them into resources/fonts/faces.json; this decides which of them the interface
REFERS to by name, and turns both into contract/include/aster/font_metrics.h.

A named size is a role, and a role is not a restatement of a baked number --
it is the UI's statement about what it means. So the roles live here, and each
is checked against the bake record: a role with no face behind it stops the
generator rather than letting a caller compile against a size nobody baked.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# The body face: everything the chrome draws with. Also what the SDK's
# ASTER_TEXT_FACES[0] resolves to, and so the size every app in the tree
# inherits.
UI_PX = 20
# The small face: one line under an icon in the app drawer, where the tile is
# 123 px tall and the 96 px well leaves room for exactly one line box (see
# LAUNCHER_LABEL_H). A separate face rather than a scaled one, because a
# cpfont is bitmaps at one size.
CAPTION_PX = 16


def role(faces, px, macro):
    for face in faces:
        if face["px"] == px:
            return face
    baked = ", ".join(str(face["px"]) for face in faces)
    raise SystemExit(f"{macro} is {px} px but the bake has no such face "
                     f"(it has {baked}); re-bake with "
                     f"tools/build_cpfont.py --sizes {baked}")


def render():
    document = json.loads((ROOT / "resources/fonts/faces.json").read_text())
    ui = role(document["faces"], UI_PX, "ASTER_FONT_UI_PX")
    caption = role(document["faces"], CAPTION_PX, "ASTER_FONT_CAPTION_PX")
    # UI face first. The SDK writes `ASTER_TEXT_FACES[] = ASTER_FONT_FACE_METRICS`
    # and every app takes ASTER_TEXT_FACES[0] as its own text size, so the order
    # of the bake record would otherwise decide how big every app draws. A
    # re-bake that lists the sizes differently must not be able to change that.
    faces = sorted(document["faces"], key=lambda face: face["px"] != ui["px"])
    sizes = ", ".join(str(face["px"]) for face in faces)
    metrics = ", ".join("{ %d, %d, %d }" % (face["px"], face["line_h"], face["asc"]) for face in faces)
    return f'''/* SPDX-License-Identifier: MIT; generated by tools/font_metrics.py */
#ifndef ASTER_FONT_METRICS_H
#define ASTER_FONT_METRICS_H
#define ASTER_FONT_BAKED_PX {{ {sizes} }}
#define ASTER_FONT_BAKED_N {len(faces)}u
#define ASTER_FONT_FACE_METRICS {{ {metrics} }}
#define ASTER_FONT_MAX_BMP {document['max_bmp']}u
#define ASTER_FONT_MAX_SCRATCH {document['max_scratch']}u
#define ASTER_FONT_UI_PX {ui['px']}
#define ASTER_FONT_UI_LINE_H {ui['line_h']}
#define ASTER_FONT_UI_ASC {ui['asc']}
#define ASTER_FONT_CAPTION_PX {caption['px']}
#define ASTER_FONT_CAPTION_LINE_H {caption['line_h']}
#define ASTER_FONT_CAPTION_ASC {caption['asc']}
#endif
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header = ROOT / "contract/include/aster/font_metrics.h"
    if args.check:
        if not header.exists() or header.read_text() != render():
            raise SystemExit("font contract differs from resource metadata; run tools/font_metrics.py")
    else:
        header.write_text(render())
